"""Generate portable CSS variables from the Vi Learn JSON source, without dependencies."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def render():
    data = json.loads((ROOT / 'tokens/design-tokens.json').read_text())
    shared = []
    for group in ['spacing', 'radius', 'borderWidth', 'size', 'layout']:
        prefix = {'spacing': 'space', 'borderWidth': 'border'}.get(group, group)
        shared.extend(f'  --vl-{prefix}-{key}: {value}px;' for key, value in data[group].items())
    shared.extend(f'  --vl-font-{key}: {value};' for key, value in data['font'].items())
    for name, role in data['typography'].items():
        for key in ['size', 'lineHeight', 'weight', 'tracking']:
            suffix = {'lineHeight': 'line-height'}.get(key, key)
            unit = 'px' if key == 'size' else ''
            shared.append(f'  --vl-type-{name}-{suffix}: {role[key]}{unit};')
    for key, value in data['motion']['duration'].items():
        shared.append(f'  --vl-duration-{key}: {value}ms;')
    shared.extend(f'  --vl-ease-{k}: {v};' for k, v in data['motion']['easing'].items())
    shared.extend(f'  --vl-layer-{k}: {v};' for k, v in data['layer'].items())
    shared.extend(f'  --vl-shadow-{k}: {v};' for k, v in data['shadow'].items())
    for palette, stops in data['color']['primitive'].items():
        shared.extend(f'  --vl-color-{palette}-{k}: {v};' for k, v in stops.items())

    def theme(name, selector):
        lines = [f'  color-scheme: {name};']
        lines.extend(f'  --vl-{k}: {v};' for k, v in data['color']['themes'][name].items())
        return selector + ' {\n' + '\n'.join(lines) + '\n}\n'

    css = '/* Generated by tools/build_tokens.py. Edit design-tokens.json. */\n'
    css += ':root {\n' + '\n'.join(shared) + '\n}\n\n'
    css += theme('light', ':root, [data-theme="light"]') + '\n'
    css += theme('dark', '[data-theme="dark"]') + '\n'
    css += '@media (prefers-color-scheme: dark) {\n' + theme('dark', ':root:not([data-theme])') + '}\n'
    for key, minimum, property_name in [
        ('tabletSize', 735, 'marketing-tablet'),
        ('desktopSize', 1069, 'marketing-desktop'),
        ('wideSize', 1441, 'marketing-xl'),
    ]:
        assert data['breakpoint'][property_name] == minimum
        changes = [f'  --vl-type-{name}-size: {role[key]}px;' for name, role in data['typography'].items() if key in role]
        css += f'@media (min-width: {minimum}px) {{\n:root {{\n' + '\n'.join(changes) + '\n}\n}\n'
    css += '@media (prefers-reduced-motion: reduce) {\n:root {\n'
    css += '\n'.join(f'  --vl-duration-{k}: 0ms;' for k in data['motion']['duration']) + '\n}\n}\n'
    return css


def build():
    css = render()
    (ROOT / 'tokens/design-tokens.css').write_text(css)
    return css


if __name__ == '__main__':
    result = build()
    print(f'Generated {len(result)} bytes of CSS')
